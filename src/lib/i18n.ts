export const messages = { ru, en }

export type MessageKey = string

type Leaf = string | { [k: string]: Leaf }

function lookup(tree: Leaf, path: string): string | undefined {
  const parts = path.split('.')
  let cur: Leaf = tree
  for (const part of parts) {
    if (typeof cur === 'string' || !(part in cur)) return undefined
    cur = cur[part]
  }
  return typeof cur === 'string' ? cur : undefined
}

export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let text = lookup(messages[locale] as Leaf, key) ?? lookup(messages.ru as Leaf, key) ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v))
    }
  }
  return text
}

export function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem('chroniqe-lang')
    if (saved === 'en' || saved === 'ru') return saved
  } catch {
    /* ignore */
  }
  const nav = typeof navigator === 'undefined' ? 'ru' : navigator.language.toLowerCase()
  return nav.startsWith('en') ? 'en' : 'ru'
}

export function msg(key: string, vars?: Record<string, string | number>): string {
  return translate(detectLocale(), key, vars)
}

export function dateLocale(): string {
  return detectLocale() === 'en' ? 'en-US' : 'ru-RU'
}

export type ThemePref = 'light' | 'dark' | 'system'

export function detectTheme(): ThemePref {
  try {
    const saved = localStorage.getItem('chroniqe-theme')
    if (saved === 'light' || saved === 'dark' || saved === 'system') return saved
  } catch {
    /* ignore */
  }
  return 'system'
}

export function resolveTheme(pref: ThemePref): 'light' | 'dark' {
  if (pref === 'system') {
    return window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light'
  }
  return pref
}
